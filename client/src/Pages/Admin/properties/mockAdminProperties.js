export const formatPrice = (amount, demandType = 'Sale') => {
  if (!amount || isNaN(amount)) return 'Price on Request';
  const num = Number(amount);
  if (demandType === 'Rent') {
    return `PKR ${num.toLocaleString('en-PK')} / mo`;
  }
  if (num >= 10000000) {
    const crore = (num / 10000000).toFixed(2).replace(/\.00$/, '');
    return `PKR ${crore} Crore`;
  }
  if (num >= 100000) {
    const lakh = (num / 100000).toFixed(2).replace(/\.00$/, '');
    return `PKR ${lakh} Lakh`;
  }
  return `PKR ${num.toLocaleString('en-PK')}`;
};
